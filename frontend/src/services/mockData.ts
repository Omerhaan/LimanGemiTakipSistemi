class MockStorage {
  private readonly VERSION_KEY = 'mock_data_version';
  private readonly CURRENT_VERSION = 'v8_full_crew_assignments';

  constructor() {
    this.checkVersion();
  }

  private checkVersion(): void {
    try {
      const version = localStorage.getItem(this.VERSION_KEY);
      if (version !== this.CURRENT_VERSION) {
        this.resetAll();
        localStorage.setItem(this.VERSION_KEY, this.CURRENT_VERSION);
      }
    } catch {
      // LocalStorage might be disabled or unavailable in some contexts
    }
  }

  private get<T>(key: string, initial: T): T {
    const data = localStorage.getItem(`mock_${key}`);
    if (!data) {
      this.set(key, initial);
      return initial;
    }
    try {
      return JSON.parse(data);
    } catch (e) {
      console.warn(`JSON parse error for mock_${key}, falling back to initial data.`, e);
      return initial;
    }
  }

  private set<T>(key: string, value: T): void {
    localStorage.setItem(`mock_${key}`, JSON.stringify(value));
  }

  getShips(): Ship[] {
    return this.get<Ship[]>('ships', INITIAL_SHIPS);
  }

  saveShips(ships: Ship[]): void {
    this.set('ships', ships);
  }

  getPorts(): Port[] {
    return this.get<Port[]>('ports', INITIAL_PORTS);
  }

  savePorts(ports: Port[]): void {
    this.set('ports', ports);
  }

  getVisits(): ShipVisit[] {
    return this.get<ShipVisit[]>('visits', INITIAL_VISITS);
  }

  saveVisits(visits: ShipVisit[]): void {
    this.set('visits', visits);
  }

  getCargoes(): Cargo[] {
    return this.get<Cargo[]>('cargoes', INITIAL_CARGOES);
  }

  saveCargoes(cargoes: Cargo[]): void {
    this.set('cargoes', cargoes);
  }

  getCrew(): CrewMember[] {
    return this.get<CrewMember[]>('crew', INITIAL_CREW);
  }

  saveCrew(crew: CrewMember[]): void {
    this.set('crew', crew);
  }

  getAssignments(): ShipCrewAssignment[] {
    return this.get<ShipCrewAssignment[]>('assignments', INITIAL_ASSIGNMENTS);
  }

  saveAssignments(assignments: ShipCrewAssignment[]): void {
    this.set('assignments', assignments);
  }

  resetAll(): void {
    localStorage.removeItem('mock_ships');
    localStorage.removeItem('mock_ports');
    localStorage.removeItem('mock_visits');
    localStorage.removeItem('mock_cargoes');
    localStorage.removeItem('mock_crew');
    localStorage.removeItem('mock_assignments');
  }
}

